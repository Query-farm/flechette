/**
 * Encode multiple Arrow tables into a single Arrow IPC stream.
 *
 * Each input table contributes its record batches to the output stream in
 * order — the result is a multi-batch IPC stream that downstream readers
 * (PyArrow, arrow-js, flechette itself) consume in one pass. All input
 * tables MUST share an equivalent schema (same field count and names; the
 * first table's schema is used for the output).
 *
 * Equivalent to concatenating multiple single-table IPC streams except the
 * intermediate schema headers and EOS markers are stripped — naive
 * concatenation produces a stream with multiple EOS markers, which causes
 * readers to stop after the first table's batches.
 *
 * Dictionaries: ids are assigned by field position (depth-first over the
 * first table's schema), not by object identity, so every table maps its
 * Dictionary fields to the same ids. Each table may carry its own dictionary
 * values: the first table to contribute data defines each dictionary up front,
 * and a later table whose dictionary differs emits a replacement dictionary
 * batch immediately before its first record batch. Record batches therefore
 * always resolve against the dictionary of the table they came from, the
 * stream-format behaviour Apache Arrow JS's writer also has. (A table that
 * reuses the previous table's dictionary column emits nothing new.) The file
 * format forbids replacements, so divergent dictionaries throw there.
 *
 * @param {Table[]} tables The Arrow tables to encode (must share a schema).
 * @param {object} [options] Encoding options.
 * @param {Sink} [options.sink] IPC byte consumer.
 * @param {'stream' | 'file'} [options.format] Arrow stream or file format.
 * @param {CompressionType_ | null} [options.codec] Compression codec to apply.
 * @param {(Map<string, string> | null | undefined)[]} [options.batchMetadata]
 *  Positional per-record-batch custom_metadata across the combined output
 *  stream; entry `i` is attached to the `i`-th emitted record batch.
 * @returns {Uint8Array | null} The generated bytes (for an in-memory sink)
 *  or null (if using a sink that writes bytes elsewhere).
 */
export function tablesToIPC(tables, options) {
  if (!tables || tables.length === 0) {
    throw new Error('tablesToIPC requires at least one table');
  }
  // Per-table path stays simple — the per-record-batch custom_metadata
  // pulled from `t._vgiRecordMetadata` flows through `tableToIPC`'s
  // batchMetadata option.
  if (tables.length === 1) {
    const tm = tables[0]?._vgiRecordMetadata;
    const opts = tm && !options?.batchMetadata
      ? { ...options, batchMetadata: [tm] }
      : options;
    return tableToIPC(tables[0], opts);
  }
  return multiTableToIPC(tables, options);
}

/**
 * Throw unless every table has the first table's field count and names.
 * @param {Table[]} tables
 * @param {string} caller Name used in error messages.
 */
function checkSameFields(tables, caller) {
  const headFields = tables[0].schema.fields;
  for (let i = 1; i < tables.length; i++) {
    const fields = tables[i].schema.fields;
    if (fields.length !== headFields.length) {
      throw new Error(`${caller}: table at index ${i} has ${fields.length} fields, expected ${headFields.length}`);
    }
    for (let f = 0; f < headFields.length; f++) {
      if (fields[f].name !== headFields[f].name) {
        throw new Error(
          `${caller}: table at index ${i} field[${f}] name is '${fields[f].name}', expected '${headFields[f].name}'`,
        );
      }
    }
  }
}

/**
 * Collect the Dictionary types reachable from `type`, depth-first: a
 * dictionary, then the types inside its values, then child fields in order.
 * The position in the resulting array is the dictionary id.
 * @param {any} type
 * @param {any[]} out
 */
function collectDictionaryTypes(type, out) {
  if (type?.typeId === Type.Dictionary) {
    out.push(type);
    collectDictionaryTypes(type.dictionary, out);
  }
  type?.children?.forEach((field) => collectDictionaryTypes(field.type, out));
}

/**
 * The dictionary value Columns of one table's first batch, in the same
 * depth-first order as `collectDictionaryTypes` (null where absent).
 * @param {any} type
 * @param {any} batch
 * @param {any[]} out
 */
function collectDictionaryColumns(type, batch, out) {
  if (type?.typeId === Type.Dictionary) {
    const column = batch?.dictionary ?? null;
    out.push(column);
    collectDictionaryColumns(type.dictionary, column?.data?.[0], out);
  }
  type?.children?.forEach((field, i) => collectDictionaryColumns(field.type, batch?.children?.[i], out));
}

/**
 * Clone `type` with dictionary ids stamped in depth-first order.
 * @param {any} type
 * @param {{ next: number }} counter Shared across all fields of a schema.
 * @returns {any}
 */
function stampDictionaryIds(type, counter) {
  if (type?.typeId === Type.Dictionary) {
    const id = counter.next++;
    return { ...type, id, dictionary: stampDictionaryIds(type.dictionary, counter) };
  }
  if (type?.children) {
    return { ...type, children: type.children.map((f) => ({ ...f, type: stampDictionaryIds(f.type, counter) })) };
  }
  return type;
}

/** Assemble + encode IPC for a sequence of Tables sharing a schema,
 *  preserving per-table batch positions even when some tables are
 *  metadata-only with zero column-data batches, and emitting each table's
 *  own dictionaries (see `tablesToIPC`). */
function multiTableToIPC(tables, options) {
  const id = options?.codec;
  const codec = getCompressionCodec(id);
  if (id != null && !codec) throw new Error(missingCodec(id));

  checkSameFields(tables, 'tablesToIPC');
  const headSchema = tables[0].schema;
  const headFields = headSchema.fields;

  /** Dictionary types by id (field position, depth-first). */
  const dictTypes = [];
  headFields.forEach((f) => collectDictionaryTypes(f.type, dictTypes));
  /** The dictionary value Column last emitted for each id. */
  const emitted = Array.from({ length: dictTypes.length }, () => undefined);
  /** Dictionary batches defined up front, before any record batch. */
  const dictionaries = [];

  /** @type {any[]} */
  const records = [];
  /** @type {(Map<string,string> | undefined)[]} */
  const batchMetadata = [];

  for (const t of tables) {
    const tm = t?._vgiRecordMetadata;
    const cols = t.children;
    // Number of actual record batches this table contributes (first
    // column's data array length — all columns share batch shape).
    const actualBatches = cols?.[0]?.data?.length ?? 0;

    if (actualBatches > 0) {
      // This table's dictionaries: define (first use) or replace (changed).
      const columns = [];
      cols.forEach((col) => collectDictionaryColumns(col.type, col.data[0], columns));
      const replacements = [];
      columns.forEach((column, dictId) => {
        if (!column || emitted[dictId] === column) return;
        const target = emitted[dictId] === undefined ? dictionaries : replacements;
        for (let i = 0; i < column.data.length; ++i) {
          target.push({ id: dictId, isDelta: i > 0, data: assembleSingleBatch([column], i, codec) });
        }
        emitted[dictId] = column;
      });

      for (let i = 0; i < actualBatches; i++) {
        const rec = assembleSingleBatch(cols, i, codec);
        if (i === 0 && replacements.length) rec.dictionaries = replacements;
        records.push(rec);
        batchMetadata.push(i === 0 ? tm : undefined);
      }
    } else if (tm) {
      // Empty data + metadata → synthesise one empty record batch with
      // proper FieldNodes / region descriptors derived from the schema.
      const nodes = [];
      const regions = [];
      const variadic = [];
      for (const f of headFields) {
        _appendEmptyNodes(f.type, nodes, regions, variadic);
      }
      records.push({ length: 0, nodes, regions, variadic, buffers: [], byteLength: 0 });
      batchMetadata.push(tm);
    }
    // Tables with no data and no metadata are dropped entirely (same
    // as legacy concatTables behaviour).
  }

  // Every id a record batch can reference must be defined, even when no
  // table carried data for it (e.g. only metadata-only batches): emit an
  // empty dictionary, as `tableToIPC` does for the same case.
  if (records.length) {
    dictTypes.forEach((type, dictId) => {
      if (emitted[dictId] !== undefined) return;
      const nodes = [];
      const regions = [];
      const variadic = [];
      _appendEmptyNodes(type.dictionary, nodes, regions, variadic);
      dictionaries.push({
        id: dictId,
        isDelta: false,
        data: { length: 0, nodes, regions, variadic, buffers: [], byteLength: 0 },
      });
    });
  }

  // Per-record-batch custom_metadata: the caller's positional
  // `batchMetadata` option wins; otherwise each table's own metadata
  // rides on its first record batch.
  const positional = options?.batchMetadata;
  for (let i = 0; i < records.length; i++) {
    const md = positional ? positional[i] : batchMetadata[i];
    if (md && md.size > 0) records[i].metadata = md;
  }

  const counter = { next: 0 };
  const fields = headFields.map((f) => ({ ...f, type: stampDictionaryIds(f.type, counter) }));
  const data = { schema: { ...headSchema, fields }, dictionaries, records };
  return encodeIPC(data, { ...options, codec: id }).finish();
}

/** Assemble one record batch (`columns`'s batchIndex-th batch) into the
 *  RecordBatch struct flechette's encoder expects. Mirrors the
 *  `assembleRecordBatch` helper inside `table-to-ipc.js`. */
function assembleSingleBatch(columns, batchIndex, codec) {
  let byteLength = 0;
  const nodes = [];
  const regions = [];
  const buffers = [];
  const variadic = [];

  const ctx = {
    node(length, nullCount) { nodes.push({ length, nullCount }); },
    buffer(b) {
      const bytes = new Uint8Array(b.buffer, b.byteOffset, b.byteLength);
      const buf = codec ? compressBuffer(bytes, codec) : bytes;
      const length = buf.byteLength;
      regions.push({ offset: byteLength, length });
      buffers.push(buf);
      byteLength += ((length + 7) & ~7);
    },
    variadic(length) { variadic.push(length); },
    children(type, batch) {
      type.children.forEach((field, index) => {
        _visit(field.type, batch.children[index], ctx);
      });
    },
  };

  for (const column of columns) {
    _visit(column.type, column.data[batchIndex], ctx);
  }
  return { byteLength, nodes, regions, variadic, buffers };
}

/** Recursive per-field visitor mirroring `table-to-ipc.js#visit`. Lifted
 *  here so the multi-table path doesn't need to import private helpers. */
function _visit(type, batch, ctx) {
  const { typeId } = type;
  ctx.node(batch.length, batch.nullCount);
  if (typeId === Type.Null) return;
  switch (typeId) {
    case Type.Bool:
    case Type.Int:
    case Type.Time:
    case Type.Duration:
    case Type.Float:
    case Type.Date:
    case Type.Timestamp:
    case Type.Decimal:
    case Type.Interval:
    case Type.FixedSizeBinary:
    case Type.Dictionary:
      ctx.buffer(batch.validity); ctx.buffer(batch.values); return;
    case Type.Utf8:
    case Type.LargeUtf8:
    case Type.Binary:
    case Type.LargeBinary:
      ctx.buffer(batch.validity); ctx.buffer(batch.offsets); ctx.buffer(batch.values); return;
    case Type.BinaryView:
    case Type.Utf8View:
      ctx.buffer(batch.validity); ctx.buffer(batch.values);
      ctx.variadic(batch.data.length);
      batch.data.forEach((b) => ctx.buffer(b));
      return;
    case Type.List:
    case Type.LargeList:
    case Type.Map:
      ctx.buffer(batch.validity); ctx.buffer(batch.offsets);
      ctx.children(type, batch); return;
    case Type.ListView:
    case Type.LargeListView:
      ctx.buffer(batch.validity); ctx.buffer(batch.offsets); ctx.buffer(batch.sizes);
      ctx.children(type, batch); return;
    case Type.FixedSizeList:
    case Type.Struct:
      ctx.buffer(batch.validity); ctx.children(type, batch); return;
    case Type.RunEndEncoded:
      ctx.children(type, batch); return;
    case Type.Union: {
      ctx.buffer(batch.typeIds);
      if (type.mode === UnionMode.Dense) ctx.buffer(batch.offsets);
      ctx.children(type, batch);
      return;
    }
    default:
      throw new Error(`Unsupported type: ${typeId}`);
  }
}

/** Mirror of the `appendEmptyNodes` helper in table-to-ipc.js — kept
 *  here to avoid cross-file imports for an internal helper. */
function _appendEmptyNodes(type, nodes, regions, variadic) {
  nodes.push({ length: 0, nullCount: 0 });
  if (type.typeId === Type.Null) return;
  switch (type.typeId) {
    case Type.Bool:
    case Type.Int:
    case Type.Time:
    case Type.Duration:
    case Type.Float:
    case Type.Date:
    case Type.Timestamp:
    case Type.Decimal:
    case Type.Interval:
    case Type.FixedSizeBinary:
    case Type.Dictionary:
      regions.push({ offset: 0, length: 0 });
      regions.push({ offset: 0, length: 0 });
      return;
    case Type.Utf8:
    case Type.LargeUtf8:
    case Type.Binary:
    case Type.LargeBinary:
      regions.push({ offset: 0, length: 0 });
      regions.push({ offset: 0, length: 0 });
      regions.push({ offset: 0, length: 0 });
      return;
    case Type.BinaryView:
    case Type.Utf8View:
      regions.push({ offset: 0, length: 0 });
      regions.push({ offset: 0, length: 0 });
      variadic.push(0);
      return;
    case Type.List:
    case Type.LargeList:
    case Type.Map:
      regions.push({ offset: 0, length: 0 });
      regions.push({ offset: 0, length: 0 });
      type.children?.forEach((c) => _appendEmptyNodes(c.type, nodes, regions, variadic));
      return;
    case Type.FixedSizeList:
    case Type.Struct:
      regions.push({ offset: 0, length: 0 });
      type.children?.forEach((c) => _appendEmptyNodes(c.type, nodes, regions, variadic));
      return;
    default:
      regions.push({ offset: 0, length: 0 });
      regions.push({ offset: 0, length: 0 });
  }
}

// concatTables is exported below — `tablesToIPC` is just a thin wrapper that
// concatenates first then encodes.

/**
 * Concatenate multiple Tables (sharing a schema) row-wise into a single
 * Table whose Columns carry every input's batches in order. Existing batch
 * boundaries are preserved — if input table A has 2 batches and B has 3,
 * the result has 5 batches in `[A0, A1, B0, B1, B2]` order. (When you then
 * encode via `tablesToIPC` / `tableToIPC`, each batch becomes one IPC
 * record message, so the wire stream has 5 records.)
 *
 * The new Table reuses the first input's schema and per-column types.
 * Inputs must agree on field count and field names; type compatibility
 * beyond that is the caller's responsibility.
 *
 * @param {Table[]} tables The Arrow tables to concatenate.
 * @returns {Table} A new Table with batches drawn from every input in order.
 */
export function concatTables(tables) {
  if (!tables || tables.length === 0) {
    throw new Error('concatTables requires at least one table');
  }
  if (tables.length === 1) return tables[0];

  const head = tables[0];
  const headFields = head.schema.fields;

  // Validate schema compatibility before allocating.
  checkSameFields(tables, 'concatTables');

  // For each column position, concatenate the per-table batches into a
  // single Column. The first table's column type is authoritative; other
  // tables' batches are appended assuming type-compatibility.
  const mergedChildren = headFields.map((_, colIdx) => {
    const headCol = head.children[colIdx];
    const allBatches = [];
    for (const t of tables) {
      const col = t.children[colIdx];
      for (const b of col.data) allBatches.push(b);
    }
    return new Column(allBatches, headCol.type);
  });

  return new Table_(head.schema, mergedChildren);
}
